/*
链接器做的事可以概括为三件：

沿用"合订成书"的比喻，三步就是合订时依次做的三件事。

1. 符号解析：找到"谁有"

第 1 章里写着"详见 `add`"，链接器要去其他章里找，哪一章真的写了 `add`。

找到了就配对成功，找不到就报 `Undefined symbols`，找到两章都有就报 `duplicate symbol`。这一步只回答**"在哪个文件里"**，还没有涉及具体位置。

2. 合并段：排版，决定每样东西放哪

每个 `.o` 里的内容分成几类，叫"段"：

- **代码段**：函数的机器指令
- **数据段**：全局变量等数据

链接器把所有 `.o` 的代码段拼成一大块，数据段拼成另一大块，然后算出每个函数、每个变量最终在可执行文件的**第几个位置**。就像把各章拼在一起后，才知道第 5 章从第 87 页开始。

3. 重定位：回头把空填上

编译 `main.cpp` 时，调用 `add` 的那条指令里，地址是空着的。第 2 步算出 `add` 的位置后，链接器回去把这个空填上。就像把"详见第 5 章"改成"详见第 87 页"。

## 为什么是这个顺序

```
第1步 找到谁有 add  →  第2步 排版，算出 add 在哪  →  第3步 把地址填进调用处
```

不先排版就不知道页码，不知道页码就没法回填，所以后一步依赖前一步。

## 对应到 `main` 和 `add`

| 步骤 | 链接器做的事 |
|---|---|
| 1 | `main.o` 需要 `add`，`add.o` 有 `add`，配对成功 |
| 2 | 把 `main` 和 `add` 的代码拼在一起，算出 `add` 在地址 `0x100000490` |
| 3 | 回到 `main` 里那条调用指令，把空着的目标改成 `0x100000490` |



本质就是一件把"我需要 X"和"我有 X"配对，上面的都是实现细节。

g++ -c main.cpp -o main.o       # 1
g++ main.o -o app               # 2
g++ main.o add.o -o app         # 3


1.只编译不链接，成功。 说明编译 main.cpp 时不需要 add 的实现，只要声明就够了。
2.只链接 main.o，报错。 会看到 Undefined symbols: "add(int, int)"。意思是合订时发现"详见 add"，但没有任何一章有 add，对不上，所以失败。
3.加上 add.o，成功。 对上了，链接完成。
*/

int add(int a, int b);

int main()
{
    return add(1, 2);
}